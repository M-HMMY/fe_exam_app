- 処理の履歴（**監査証跡／アクセスログ**）が取得され、**改ざんされずに保存** されていること
- 入力から出力までの流れを追跡できること（**トレーサビリティ**）
- 誰が何を行ったかを特定できること（**責任追跡性**）

